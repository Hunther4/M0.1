    def _handle_audio_restart(self):
        logger.info("[JARVIS] 🔄 Audio settings updated, requesting restart...")
        self._restart_audio = True

    async def _listen_audio(self):
        logger.info("[JARVIS] 🎤 Mic started")
        loop = asyncio.get_event_loop()
        
        self.audio_buffer = []
        self.silence_count = 0
        self._buffer_bytes = 0
        self.MAX_BUFFER_BYTES = 30 * 16000 * 2  # ~960KB (~30s at 32KB/s)
        self.silence_chunks_limit = int(1.2 * (SEND_SAMPLE_RATE / CHUNK_SIZE))
        self.amplitude_threshold = config.get_config().get("amplitude_threshold", 50)  # RMS threshold
        
        def callback(indata, frames, time_info, status):
            is_speaking = getattr(self.orchestrator.tts, "is_speaking", False)
            ptt_active  = getattr(self.ui, "ptt_active", False)
            if is_speaking or not ptt_active:
                # Flush buffer when PTT is released so we don't process stale audio
                if not ptt_active and self.audio_buffer:
                    complete_audio = b"".join(self.audio_buffer)
                    self.audio_buffer = []
                    self.silence_count = 0
                    self._buffer_bytes = 0
                    asyncio.run_coroutine_threadsafe(
                        self.orchestrator.process_voice_input(complete_audio),
                        loop
                    )
                return

                
            data = indata.tobytes()
            # Calculate RMS to detect voice activity
            chunk_np = np.frombuffer(data, dtype=np.int16)
            rms = np.sqrt(max(0, np.mean(chunk_np**2))) if len(chunk_np) > 0 else 0
            
            if rms > self.amplitude_threshold:
                self.audio_buffer.append(data)
                self._buffer_bytes += len(data)
                self.silence_count = 0
            else:
                if self.audio_buffer:
                    self.audio_buffer.append(data)
                    self._buffer_bytes += len(data)
                    self.silence_count += 1
                    
                    # Force-trigger if buffer exceeds max (prevents OOM on long pauses)
                    force = self._buffer_bytes >= self.MAX_BUFFER_BYTES
                    if force or self.silence_count >= self.silence_chunks_limit:
                        complete_audio = b"".join(self.audio_buffer)
                        self.audio_buffer = []
                        self.silence_count = 0
                        self._buffer_bytes = 0
                        
                        asyncio.run_coroutine_threadsafe(
                            self.orchestrator.process_voice_input(complete_audio),
                            loop
                        )

        while True:
            try:
                mic_idx = config.get_config().get("mic_device_index", None)
                try:
                    with sd.InputStream(
                        device=mic_idx,
                        samplerate=SEND_SAMPLE_RATE,
                        channels=CHANNELS,
                        dtype="int16",
                        blocksize=CHUNK_SIZE,
                        callback=callback,
                    ):
                        logger.info(f"[JARVIS] 🎤 Mic stream open (device={mic_idx})")
                        while True:
                            if self._restart_audio:
                                self._restart_audio = False
                                break
                            await asyncio.sleep(0.1)
                except Exception as e:
                    logger.warning(f"[JARVIS] ⚠️ Mic device {mic_idx} failed: {e}. Falling back to system default.")
                    if mic_idx is not None:
                        with sd.InputStream(
                            device=None,
                            samplerate=SEND_SAMPLE_RATE,
                            channels=CHANNELS,
                            dtype="int16",
                            blocksize=CHUNK_SIZE,
                            callback=callback,
                        ):
                            logger.info("[JARVIS] 🎤 Mic stream open (device=None fallback)")
                            while True:
                                if self._restart_audio:
                                    self._restart_audio = False
                                    break
                                await asyncio.sleep(0.1)
                    else:
                        raise e
            except Exception as e:
                logger.error(f"[JARVIS] ❌ Mic fatal error: {e}")
                await asyncio.sleep(3)

    async def run(self):
        self._loop = asyncio.get_event_loop()
        self.ui.set_state("LISTENING")
        self.ui.write_log(f"[sys] {_('jarvis_online')}")
        
        await self._listen_audio()

